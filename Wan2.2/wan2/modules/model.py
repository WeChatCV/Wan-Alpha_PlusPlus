    def load_dora(self, dora_path, alpha):
        def get_name_dict(dora_state_dict):
            dora_name_dict = {}
            for key in dora_state_dict:
                # 识别lora_B参数，作为主key关联其他参数
                if ".lora_B." not in key:
                    continue
                # 解析基础层名称（不含适配器相关后缀）
                keys = key.split(".")
                lora_b_idx = keys.index("lora_B")
                # 移除lora_B及适配器名称（如"default"）
                if len(keys) > lora_b_idx + 2:
                    keys.pop(lora_b_idx + 1)  # 移除适配器名称
                keys.pop(lora_b_idx)  # 移除"lora_B"
                # 兼容可能的前缀（如"diffusion_model"）
                if keys[0] == "diffusion_model":
                    keys.pop(0)
                target_name = ".".join(keys)
                
                # 关联lora_A、lora_magnitude_vector参数
                lora_a_key = key.replace(".lora_B.", ".lora_A.")
                # DoRA的幅度向量参数键通常格式为：xxx.lora_magnitude_vector.<adapter_name>.weight
                magnitude_key = key.replace(".lora_B.", ".lora_magnitude_vector.").replace(".weight", ".weight")
                # 处理可能的适配器名称差异（如将"lora_B.default"替换为"lora_magnitude_vector.default"）
                magnitude_key = magnitude_key.replace("lora_B", "lora_magnitude_vector")
                
                dora_name_dict[target_name] = {
                    "lora_B": key,
                    "lora_A": lora_a_key,
                    "magnitude": magnitude_key
                }
            return dora_name_dict

        # 加载DoRA权重（支持safetensors或pt格式）
        state_dict_dora = {}
        with safe_open(dora_path, framework="pt") as f:
            for k in f.keys():
                state_dict_dora[k] = f.get_tensor(k)
        
        # 解析参数键映射
        dora_name_dict = get_name_dict(state_dict_dora)
        state_dict_model = self.state_dict()

        for name in dora_name_dict:
            # 1. 加载DoRA的三个核心参数
            param_info = dora_name_dict[name]
            # 低秩更新矩阵（LoRA部分）
            weight_b = state_dict_dora[param_info["lora_B"]]  # lora_B权重
            weight_a = state_dict_dora[param_info["lora_A"]]  # lora_A权重
            # 幅度向量（DoRA特有）
            magnitude = state_dict_dora[param_info["magnitude"]]  # γ

            # 2. 处理维度（兼容卷积层/线性层）
            if len(weight_b.shape) == 4:
                # 卷积层：移除空间维度（假设为1x1卷积）
                weight_b = weight_b.squeeze(3).squeeze(2)
                weight_a = weight_a.squeeze(3).squeeze(2)
                # 计算LoRA低秩更新 ΔW
                delta_weight = alpha * torch.mm(weight_b, weight_a)
                # 恢复卷积层维度
                delta_weight = delta_weight.unsqueeze(2).unsqueeze(3)
            else:
                # 线性层：直接计算 ΔW = α * (B @ A)
                delta_weight = alpha * torch.mm(weight_b, weight_a)

            # 3. 计算 DoRA 权重更新
            # 原始权重 W
            weight_model = state_dict_model[name].clone()

            # print(f"Layer: {name}")
            # print(f"Original weight shape: {weight_model.shape}")
            # print(f"lora_A shape: {weight_a.shape}")
            # print(f"lora_B shape: {weight_b.shape}")

            # # 计算delta_weight后
            # print(f"delta_weight shape: {delta_weight.shape}")
            # 计算 W + ΔW
            weight_with_delta = weight_model + delta_weight

            # 4. 计算列方向L2范数 ||W + ΔW||
            # 对于卷积层，范数计算在输出通道维度（假设shape为[out_ch, in_ch, 1, 1]）
            if len(weight_with_delta.shape) == 4:
                # 压缩空间维度后计算范数
                norm_dims = tuple(range(1, weight_with_delta.dim()))  # 对[in_ch, 1, 1]维度求范数
                weight_norm = torch.linalg.norm(weight_with_delta, dim=norm_dims, keepdim=True)
            else:
                # 线性层：对输入特征维度求范数（shape为[out_dim, in_dim]）
                weight_norm = torch.linalg.norm(weight_with_delta, dim=1, keepdim=True)

            # 避免除零错误
            weight_norm = torch.clamp(weight_norm, min=1e-8)

            # 5. 应用幅度缩放：W_new = (γ / ||W + ΔW||) * (W + ΔW)
            # 确保幅度向量维度与范数匹配（可能需要扩展维度）
            magnitude = magnitude.view_as(weight_norm)  # 调整γ的形状以匹配范数
            weight_patched = (magnitude / weight_norm) * weight_with_delta

            # 6. 更新模型权重
            state_dict_model[name] = weight_patched

        # 加载最终合并后的权重
        self.load_state_dict(state_dict_model)

    def forward(
        self,
        x,
        t,
        context,
        seq_len,
        y=None,
    ):
        r"""
        Forward pass through the diffusion model

        Args:
            x (List[Tensor]):
                List of input video tensors, each with shape [C_in, F, H, W]
            t (Tensor):
                Diffusion timesteps tensor of shape [B]
            context (List[Tensor]):
                List of text embeddings each with shape [L, C]
            seq_len (`int`):
                Maximum sequence length for positional encoding
            y (List[Tensor], *optional*):
                Conditional video inputs for image-to-video mode, same shape as x

        Returns:
            List[Tensor]:
                List of denoised video tensors with original input shapes [C_out, F, H / 8, W / 8]
        """
        if self.model_type == 'i2v':
            assert y is not None
        # params
        device = self.patch_embedding.weight.device
        if self.freqs.device != device:
            self.freqs = self.freqs.to(device)

        if y is not None:
            x = [torch.cat([u, v], dim=0) for u, v in zip(x, y)]

        # embeddings
        x = [self.patch_embedding(u.unsqueeze(0)) for u in x]
        grid_sizes = torch.stack(
            [torch.tensor(u.shape[2:], dtype=torch.long) for u in x])
        x = [u.flatten(2).transpose(1, 2) for u in x]
        seq_lens = torch.tensor([u.size(1) for u in x], dtype=torch.long)
        assert seq_lens.max() <= seq_len
        x = torch.cat([
            torch.cat([u, u.new_zeros(1, seq_len - u.size(1), u.size(2))],
                      dim=1) for u in x
        ])

        # time embeddings
        if t.dim() == 1:
            t = t.expand(t.size(0), seq_len)
        with torch.amp.autocast('cuda', dtype=torch.float32):
            bt = t.size(0)
            t = t.flatten()
            e = self.time_embedding(
                sinusoidal_embedding_1d(self.freq_dim,
                                        t).unflatten(0, (bt, seq_len)).float())
            e0 = self.time_projection(e).unflatten(2, (6, self.dim))
            assert e.dtype == torch.float32 and e0.dtype == torch.float32

        # context
        context_lens = None
        context = self.text_embedding(
            torch.stack([
                torch.cat(
                    [u, u.new_zeros(self.text_len - u.size(0), u.size(1))])
                for u in context
            ]))

        # arguments
        kwargs = dict(
            e=e0,
            seq_lens=seq_lens,
            grid_sizes=grid_sizes,
            freqs=self.freqs,
            context=context,
            context_lens=context_lens)

        for block in self.blocks:
            x = block(x, **kwargs)

        # head
        x = self.head(x, e)

        # unpatchify
        x = self.unpatchify(x, grid_sizes)
        return [u.float() for u in x]

    def unpatchify(self, x, grid_sizes):
        r"""
        Reconstruct video tensors from patch embeddings.

        Args:
            x (List[Tensor]):
                List of patchified features, each with shape [L, C_out * prod(patch_size)]
            grid_sizes (Tensor):
                Original spatial-temporal grid dimensions before patching,
                    shape [B, 3] (3 dimensions correspond to F_patches, H_patches, W_patches)

        Returns:
            List[Tensor]:
                Reconstructed video tensors with shape [C_out, F, H / 8, W / 8]
        """

        c = self.out_dim
        out = []
        for u, v in zip(x, grid_sizes.tolist()):
            u = u[:math.prod(v)].view(*v, *self.patch_size, c)
            u = torch.einsum('fhwpqrc->cfphqwr', u)
            u = u.reshape(c, *[i * j for i, j in zip(v, self.patch_size)])
            out.append(u)
        return out

    def init_weights(self):
        r"""
        Initialize model parameters using Xavier initialization.
        """

        # basic init
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_uniform_(m.weight)
                if m.bias is not None:
                    nn.init.zeros_(m.bias)

        # init embeddings
        nn.init.xavier_uniform_(self.patch_embedding.weight.flatten(1))
        for m in self.text_embedding.modules():
            if isinstance(m, nn.Linear):
                nn.init.normal_(m.weight, std=.02)
        for m in self.time_embedding.modules():
            if isinstance(m, nn.Linear):
                nn.init.normal_(m.weight, std=.02)

        # init output layer
        nn.init.zeros_(self.head.head.weight)
